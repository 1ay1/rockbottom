// ── the PER-CORE TABLE contract ────────────────────────────────────
// The table promises four things at EVERY terminal size and core count, and
// each is a bug someone would file if it broke:
//
//   1. ONE ROW PER CORE — exactly n core rows plus the ALL package row. A grid
//      that silently packed two cores onto a line, or dropped the tail of a
//      256-thread machine, would look plausible in a screenshot.
//   2. The USE column sits at ONE x for the header and every row, so the
//      numbers read as a column (this is issue #2, now table-shaped).
//   3. Nothing OVERFLOWS its slot — no row is longer than the pane, so no
//      number can be pushed off-screen or wrap into the row below.
//   4. Every core's LOAD is legible: its own "NN%" appears on its own row.
//
// Runs over a large matrix, so it accumulates FAILURE STRINGS rather than
// printing a PASS line per case — a hundred green lines would bury the red one.
std::vector<std::string> table_faults;

void test_core_table(int n, bool hybrid, int temp_every, int w) {
    const std::string name = "n=" + std::to_string(n) + " w=" + std::to_string(w)
                           + (hybrid ? " hybrid" : "") + " t/" + std::to_string(temp_every);
    const CpuInfo cpu = make_cpu(n, hybrid, temp_every);
    const auto rows = render_detail(make_snapshot(cpu), w, 40 + n * 3);
    auto fault = [&](const std::string& why) { table_faults.push_back(name + ": " + why); };

    // Locate the table by its header — the row carrying the USE label. Its '%'
    // rail is then the rail every core row must hit.
    int use_x = -1;
    int table_x = -1;
    for (const std::string& r : rows) {
        const std::size_t k = r.find("USE");
        const std::size_t load = r.find("LOAD");
        if (k != std::string::npos && load != std::string::npos) {
            use_x = static_cast<int>(k) + 2;   // 'USE' is right-aligned on '%'
            // The core table may be either the left or right detail rail.
            // Keep its own x-origin so summary rows on the other rail cannot
            // be mistaken for table entries.
            table_x = static_cast<int>(r.rfind("CORE", load));
            if (table_x < 0) table_x = static_cast<int>(r.rfind("CPU", load));
            break;
        }
    }
    if (use_x < 0 || table_x < 0) { fault("no table header"); return; }

    // A core row is one whose FIRST token is this table's id — count them.
    int core_rows = 0, all_rows = 0, misaligned = 0, overflow = 0;
    for (const std::string& r : rows) {
        if (static_cast<int>(r.size()) > w) ++overflow;
        // Read only the table's own left cell. In ultrawide mode another
        // column can contain bars and percentages before this table begins.
        const std::size_t begin = std::min<std::size_t>(table_x, r.size());
        const std::size_t end = std::min<std::size_t>(use_x, r.size());
        std::size_t i = begin;
        while (i < end && r[i] == ' ') ++i;
        if (i >= end) continue;
        const std::vector<int> pc = pct_columns(r);
        // A row belongs to this table only when it reaches THIS table's USE
        // rail—not merely because an adjacent summary rail contains a number.
        if (std::find(pc.begin(), pc.end(), use_x) == pc.end()) continue;
        const bool is_all = r.compare(i, 3, "ALL") == 0;
        const bool is_core = std::isdigit(static_cast<unsigned char>(r[i]));
        if (!is_all && !is_core) continue;
        if (is_all) ++all_rows; else ++core_rows;
    }
    if (core_rows != n)
        fault("expected " + std::to_string(n) + " core rows, got " + std::to_string(core_rows));
    if (all_rows != 1)
        fault("expected 1 ALL row, got " + std::to_string(all_rows));
    if (misaligned)
        fault(std::to_string(misaligned) + " row(s) off the USE rail at x=" + std::to_string(use_x));
    if (overflow)
        fault(std::to_string(overflow) + " row(s) wider than " + std::to_string(w));
}

// Terminal-escape-injection defense: process names / command lines are
// attacker-controlled, so sanitize_display() must neutralize every terminal
// control introducer while leaving legitimate UTF-8 untouched. A regression
// here silently reopens a real vulnerability, so it is asserted, not just
// eyeballed.
void test_sanitize() {
    using rockbottom::sys::sanitize_display;
    std::printf("\nsecurity — process-name escape injection is neutralized:\n");

    // A string is unsafe if, decoded as UTF-8, any codepoint is a control
    // (C0/DEL/C1) or any byte is not part of a well-formed sequence.
    auto unsafe = [](const std::string& s) {
        std::size_t i = 0, n = s.size();
        auto cont = [&](std::size_t k){ return k < n && (static_cast<unsigned char>(s[k]) & 0xC0) == 0x80; };
        while (i < n) {
            unsigned char c = static_cast<unsigned char>(s[i]);
            char32_t cp; std::size_t len;
            if (c < 0x80) { cp = c; len = 1; }
            else if ((c & 0xE0) == 0xC0 && cont(i+1)) { cp = ((c & 0x1F) << 6) | (static_cast<unsigned char>(s[i+1]) & 0x3F); len = 2; }
            else if ((c & 0xF0) == 0xE0 && cont(i+1) && cont(i+2)) { cp = (static_cast<char32_t>(c & 0x0F) << 12) | ((static_cast<unsigned char>(s[i+1]) & 0x3F) << 6) | (static_cast<unsigned char>(s[i+2]) & 0x3F); len = 3; }
            else if ((c & 0xF8) == 0xF0 && cont(i+1) && cont(i+2) && cont(i+3)) { cp = (static_cast<char32_t>(c & 0x07) << 18) | ((static_cast<char32_t>(static_cast<unsigned char>(s[i+1]) & 0x3F)) << 12) | ((static_cast<unsigned char>(s[i+2]) & 0x3F) << 6) | (static_cast<unsigned char>(s[i+3]) & 0x3F); len = 4; }
            else return true;   // malformed byte
            if (cp < 0x20 || cp == 0x7f || (cp >= 0x80 && cp <= 0x9f)) return true;
            i += len;
        }
        return false;
    };

    // Every injection payload must come out safe.
    const std::string payloads[] = {
        std::string("evil\x1b[2Jname"),        // C0 CSI (clear screen)
        std::string("t\x1b]0;pwned\x07"),      // OSC window-title / clipboard
        std::string("a\x9b" "31mRED"),          // 8-bit CSI (0x9b) — maya passes this through
        std::string("b\x9d" "x\x9c"),           // 8-bit OSC + ST
        std::string("c\x7f" "d"),               // DEL
        std::string("e\xC2\x9B" "f"),          // UTF-8-encoded C1 CSI
        std::string("\x80\x81lone"),            // lone continuation bytes
        std::string("trunc\xE4\xBD"),           // truncated 3-byte sequence
        std::string("over\xC0\x80"),            // overlong NUL
    };
    bool all_safe = true;
    for (const auto& p : payloads)
        if (unsafe(sanitize_display(p))) all_safe = false;
    check(all_safe, "all terminal-control payloads are neutralized");

    // Legitimate UTF-8 must survive byte-for-byte (no false positives that
    // would mangle real process names).
    const std::string legit = "caf\xC3\xA9 \xC2\xA0 \xE4\xBD\xA0\xE5\xA5\xBD \xF0\x9F\x9A\x80";
    check(sanitize_display(legit) == legit,
          "accents / nbsp / CJK / emoji pass through unchanged");
    check(sanitize_display("normal-proc") == "normal-proc" && sanitize_display("").empty(),
          "plain names and empty strings are unchanged");
}

void test_proc_order_strictness() {
    std::printf("\nprocess sorting is a strict weak ordering:\n");

    ProcInfo a{}, b{};
    a.pid = 20;
    b.pid = 10;
    a.name = b.name = "same";
    a.cpu = b.cpu = 42.0;
    a.rss = b.rss = Bytes{4096};
    a.io_read.per_sec = b.io_read.per_sec = 128.0;

    constexpr SortKey keys[] = {SortKey::Cpu, SortKey::Mem, SortKey::Io,
                                SortKey::Pid, SortKey::Name, SortKey::Port};
    bool irreflexive = true, antisymmetric = true;
    for (SortKey key : keys) {
        for (bool desc : {false, true}) {
            irreflexive &= !ui::proc_less(a, a, key, desc) &&
                           !ui::proc_less(b, b, key, desc);
            antisymmetric &= !(ui::proc_less(a, b, key, desc) &&
                               ui::proc_less(b, a, key, desc));
        }
    }
    check(irreflexive, "no process compares less than itself in either direction");
    check(antisymmetric, "equal primary keys use a one-way pid tiebreak");

    // Distinct values pin the direction contract too: magnitude columns are
    // naturally largest-first, while pid/name are naturally ascending.
    a.cpu = 90.0; b.cpu = 10.0;
    a.rss = Bytes{9000}; b.rss = Bytes{1000};
    a.io_read.per_sec = 900.0; b.io_read.per_sec = 100.0;
    a.name = "zeta"; b.name = "alpha";
    a.ports = {8080}; b.ports.clear();
    check(ui::proc_less(a, b, SortKey::Cpu, true) &&
          ui::proc_less(b, a, SortKey::Cpu, false),
          "cpu direction toggles largest-first / smallest-first");
    check(ui::proc_less(a, b, SortKey::Mem, true) &&
          ui::proc_less(b, a, SortKey::Mem, false),
          "memory direction toggles largest-first / smallest-first");
    check(ui::proc_less(a, b, SortKey::Io, true) &&
          ui::proc_less(b, a, SortKey::Io, false),
          "I/O direction toggles largest-first / smallest-first");
    check(ui::proc_less(b, a, SortKey::Pid, false) &&
          ui::proc_less(a, b, SortKey::Pid, true),
          "pid direction toggles ascending / descending");
    check(ui::proc_less(b, a, SortKey::Name, false) &&
          ui::proc_less(a, b, SortKey::Name, true),
          "name direction toggles A-first / Z-first");
    check(ui::proc_less(a, b, SortKey::Port, true) &&
          ui::proc_less(b, a, SortKey::Port, false),
          "port direction toggles bound-first / unbound-first");

    // Restore equal values for the deterministic tiebreak assertion.
    a.cpu = b.cpu = 42.0;
    std::vector<const ProcInfo*> rows{&a, &b};
    const auto ordered = ui::order_flat(rows, SortKey::Cpu, false);
    check(ordered.procs.size() == 2 && ordered.procs[0]->pid == 10 &&
          ordered.procs[1]->pid == 20,
          "equal-value rows have deterministic pid order");
}

