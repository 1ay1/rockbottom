// ── #2: the numeric columns must line up ─────────────────────────────
// Collect the rows that carry per-core figures and assert every one of them
// places its '%' at the same set of columns. A ragged grid produces different
// offsets per row — which is exactly what the reporter saw.
void test_alignment(const std::string& name, const std::vector<std::string>& rows,
                    Scan scan = Scan::AllColumns) {
    std::vector<std::vector<int>> shapes;
    for (const std::string& r : rows) {
        if (!is_core_row(r)) continue;
        std::vector<int> cols = pct_columns(r);
        if (cols.empty()) continue;
        if (scan == Scan::LeadingColumn) cols.resize(1);
        shapes.push_back(std::move(cols));
    }
    check(shapes.size() >= 2, name + ": found per-core rows to compare (" +
                                  std::to_string(shapes.size()) + ")");
    if (shapes.size() < 2) return;

    // Rows in a grid can hold a different NUMBER of cells (the last row may be
    // short), so compare each row's leading columns against the widest row's.
    std::size_t widest = 0;
    for (std::size_t i = 1; i < shapes.size(); ++i)
        if (shapes[i].size() > shapes[widest].size()) widest = i;

    bool aligned = true;
    std::string detail;
    for (const std::vector<int>& s : shapes) {
        for (std::size_t k = 0; k < s.size() && k < shapes[widest].size(); ++k) {
            if (s[k] != shapes[widest][k]) {
                aligned = false;
                detail = " (col " + std::to_string(k) + ": " + std::to_string(s[k]) +
                         " vs " + std::to_string(shapes[widest][k]) + ")";
                break;
            }
        }
        if (!aligned) break;
    }
    check(aligned, name + ": every core row's % lands in the same column" + detail);
}

void dump(const std::string& title, const std::vector<std::string>& rows) {
    std::printf("\n\x1b[2m--- %s ---\x1b[0m\n", title.c_str());
    for (const std::string& r : rows)
        if (!r.empty()) std::printf("\x1b[2m|\x1b[0m%s\n", r.c_str());
}

// Render the CPU detail pane body for a snapshot at a given size.
std::vector<std::string> render_detail(const Snapshot& s, int w, int h) {
    ui::detail::Ctx cx = ui::detail::Ctx::make(w, 50, 0);
    std::vector<maya::Element> col = ui::detail::cpu_body(s, cx);
    return render_rows((maya::dsl::v(std::move(col))).build(), w, h);
}

std::vector<std::string> render_body(std::vector<maya::Element> body, int w = 130, int h = 120) {
    return render_rows((maya::dsl::v(std::move(body))).build(), w, h);
}

bool contains_text(const std::vector<std::string>& rows, const std::string& needle) {
    for (const auto& row : rows)
        if (row.find(needle) != std::string::npos) return true;
    return false;
}

// ── topology fixtures ────────────────────────────────────────
// An in-memory sysfs: path -> contents. Lets the classifier be driven against
// the exact file layout of machines we don't have on hand.
using FakeFs = std::map<std::string, std::string>;

topo::ReadFile fs_reader(const FakeFs& fs) {
    return [&fs](const std::string& p) -> std::string {
        auto it = fs.find(p);
        return it == fs.end() ? std::string() : it->second;
    };
}

// Standard topology/ files: `n` logical cpus over `n/smt` physical cores.
void add_cpus(FakeFs& fs, int n, int smt = 1) {
    for (int i = 0; i < n; ++i) {
        const std::string b = "/sys/devices/system/cpu/cpu" + std::to_string(i) + "/topology/";
        fs[b + "core_id"] = std::to_string(i / smt);
        fs[b + "physical_package_id"] = "0";
    }
}

void add_scalar(FakeFs& fs, const std::string& suffix, const std::vector<long>& vals) {
    for (std::size_t i = 0; i < vals.size(); ++i)
        fs["/sys/devices/system/cpu/cpu" + std::to_string(i) + suffix] =
            std::to_string(vals[i]) + "\n";
}

std::string kinds_str(const topo::Topology& t) {
    if (t.kind.empty()) return "(homogeneous)";
    std::string s;
    for (CoreKind k : t.kind)
        s += k == CoreKind::Perf ? 'P' : k == CoreKind::Eff ? 'E' : '?';
    return s;
}

void expect_kinds(const std::string& name, const topo::Topology& t, const std::string& want) {
    const std::string got = kinds_str(t);
    check(got == want, name + ": " + got + (got == want ? "" : " (wanted " + want + ")"));
}

void test_topology() {
    std::printf("\nissue #3 — Linux topology classifier:\n");

    // Intel Core i7-12700H — 6 P cores with SMT (cpu0-11) + 8 E cores
    // (cpu12-19). The kernel names both clusters, so this must be exact.
    {
        FakeFs fs;
        add_cpus(fs, 20);
        fs["/sys/devices/cpu_core/cpus"] = "0-11\n";
        fs["/sys/devices/cpu_atom/cpus"] = "12-19\n";
        const topo::Topology t = topo::classify(20, fs_reader(fs));
        expect_kinds("alder lake i7-12700H", t, "PPPPPPPPPPPPEEEEEEEE");
        check(t.perf_label == "Performance", "alder lake: performance cluster named");
    }

    // A sparse/comma cpulist — the format is a list, not a single range.
    {
        FakeFs fs;
        add_cpus(fs, 8);
        fs["/sys/devices/cpu_core/cpus"] = "0-3,6\n";
        fs["/sys/devices/cpu_atom/cpus"] = "4,5,7\n";
        const topo::Topology t = topo::classify(8, fs_reader(fs));
        expect_kinds("sparse cpulist", t, "PPPPEEPE");
    }

    // ARM big.LITTLE (Snapdragon-style): 4 little + 4 big by DT capacity.
    {
        FakeFs fs;
        add_cpus(fs, 8);
        add_scalar(fs, "/cpu_capacity", {256, 256, 256, 256, 1024, 1024, 1024, 1024});
        const topo::Topology t = topo::classify(8, fs_reader(fs));
        expect_kinds("big.LITTLE capacity", t, "EEEEPPPP");
    }

    // Max-frequency inference, when neither of the better sources exists.
    {
        FakeFs fs;
        add_cpus(fs, 8);
        add_scalar(fs, "/cpufreq/cpuinfo_max_freq",
                   {2000000, 2000000, 2000000, 2000000, 3600000, 3600000, 3600000, 3600000});
        const topo::Topology t = topo::classify(8, fs_reader(fs));
        expect_kinds("max-freq inference", t, "EEEEPPPP");
        check(t.eff_label == "Slow", "max-freq: cluster labels are hedged (" + t.eff_label + ")");
    }

    // Homogeneous EPYC with binning scatter: clocks differ by ~1%, which is
    // NOT a cluster. Calling this hybrid would put a bogus P/E column on every
    // ordinary server — the regression this threshold exists to prevent.
    {
        FakeFs fs;
        add_cpus(fs, 16, 2);
        add_scalar(fs, "/cpufreq/cpuinfo_max_freq",
                   {3700000, 3700000, 3693000, 3700000, 3700000, 3688000, 3700000, 3700000,
                    3700000, 3695000, 3700000, 3700000, 3700000, 3700000, 3700000, 3690000});
        const topo::Topology t = topo::classify(16, fs_reader(fs));
        expect_kinds("homogeneous EPYC (binning scatter)", t, "(homogeneous)");
    }

    // Boost-clock quirk: one core certified 200MHz higher (Intel Turbo Boost
    // Max / AMD preferred core). Still one cluster.
    {
        FakeFs fs;
        add_cpus(fs, 8);
        add_scalar(fs, "/cpufreq/cpuinfo_max_freq",
                   {5000000, 4800000, 4800000, 4800000, 4800000, 4800000, 4800000, 4800000});
        const topo::Topology t = topo::classify(8, fs_reader(fs));
        expect_kinds("favoured-core boost quirk", t, "(homogeneous)");
    }

    // SMT sibling map: "Core 3" from Intel coretemp must reach BOTH threads.
    {
        FakeFs fs;
        add_cpus(fs, 16, 2);
        const topo::Topology t = topo::classify(16, fs_reader(fs));
        auto it = t.siblings.find(3);
        const bool paired = it != t.siblings.end() && it->second.size() == 2 &&
                            it->second[0] == 6 && it->second[1] == 7;
        check(paired, "physical core 3 maps to logical cpus 6 and 7");
    }

    // Multi-socket: both sockets have a "core 0", which must NOT collide.
    {
        FakeFs fs;
        for (int i = 0; i < 8; ++i) {
            const std::string b = "/sys/devices/system/cpu/cpu" + std::to_string(i) + "/topology/";
            fs[b + "core_id"] = std::to_string(i % 4);
            fs[b + "physical_package_id"] = std::to_string(i / 4);
        }
        const topo::Topology t = topo::classify(8, fs_reader(fs));
        check(t.siblings.size() == 8, "dual-socket: 8 distinct physical cores (got " +
                                          std::to_string(t.siblings.size()) + ")");
    }

    // Container with a masked /sys: no crash, no phantom cluster.
    {
        FakeFs fs;
        const topo::Topology t = topo::classify(4, fs_reader(fs));
        expect_kinds("masked /sys (container)", t, "(homogeneous)");
        check(t.phys.empty(), "masked /sys: no physical-core map");
    }

    // Partially readable capacity: refusing to guess beats mislabelling the
    // cores whose files didn't answer.
    {
        FakeFs fs;
        add_cpus(fs, 8);
        add_scalar(fs, "/cpu_capacity", {1024, 1024, 256, 256});   // only 4 of 8
        const topo::Topology t = topo::classify(8, fs_reader(fs));
        expect_kinds("partial capacity read", t, "(homogeneous)");
    }

    // Kernels that do NOT number core_id from 0. The ubuntu-24.04-arm CI
    // runner does exactly this — it numbers by MPIDR affinity, so the raw ids
    // are values like 36865 and the UI displayed them verbatim. The public
    // `phys` id must be dense and small, while the sensor-matching map keeps
    // the kernel's own numbering.
    {
        FakeFs fs;
        for (int i = 0; i < 4; ++i) {
            const std::string b = "/sys/devices/system/cpu/cpu" + std::to_string(i) + "/topology/";
            fs[b + "core_id"] = std::to_string(36865 + i);
            fs[b + "physical_package_id"] = "0";
        }
        const topo::Topology t = topo::classify(4, fs_reader(fs));
        const bool dense = t.phys.size() == 4 && t.phys[0] == 0 && t.phys[1] == 1 &&
                           t.phys[2] == 2 && t.phys[3] == 3;
        check(dense, "MPIDR core_ids are renumbered densely 0..3");
        check(t.by_core_id.count(36867) == 1,
              "kernel core_id 36867 still resolvable for sensor matching");
    }

    // Dense ids must not merge SMT siblings or collapse sockets.
    {
        FakeFs fs;
        add_cpus(fs, 16, 2);
        const topo::Topology t = topo::classify(16, fs_reader(fs));
        check(t.siblings.size() == 8, "SMT: 16 threads over 8 dense physical ids (got " +
                                          std::to_string(t.siblings.size()) + ")");
        int max_id = -1;
        for (int p : t.phys) max_id = std::max(max_id, p);
        check(max_id == 7, "SMT: dense ids stop at 7 (got " + std::to_string(max_id) + ")");
    }

    // Dual socket, dense: still 8 distinct cores, ids 0..7, no collision
    // between socket 0's "core 0" and socket 1's.
    {
        FakeFs fs;
        for (int i = 0; i < 8; ++i) {
            const std::string b = "/sys/devices/system/cpu/cpu" + std::to_string(i) + "/topology/";
            fs[b + "core_id"] = std::to_string(i % 4);
            fs[b + "physical_package_id"] = std::to_string(i / 4);
        }
        const topo::Topology t = topo::classify(8, fs_reader(fs));
        int max_id = -1;
        for (int p : t.phys) max_id = std::max(max_id, p);
        check(max_id == 7, "dual-socket: dense ids 0..7 (got max " + std::to_string(max_id) + ")");
        // Sensor matching is per-socket-ambiguous by nature; both sockets'
        // "core 0" must at least be reachable together rather than lost.
        check(t.by_core_id.at(0).size() == 2, "dual-socket: core_id 0 covers both sockets");
    }
}

// The ARM naming table — arm64 /proc/cpuinfo has no "model name" line, so
// without this every aarch64 machine reported the literal string "CPU".
// CI's ubuntu-24.04-arm runner is what exposed it.
void test_arm_names() {
    std::printf("\narm64 CPU naming (no \"model name\" in /proc/cpuinfo):\n");

    const struct { const char* impl; const char* part; const char* want; } cases[] = {
        {"0x41", "0xd0c", "ARM Neoverse-N1"},    // Graviton2 / Ampere Altra
        {"0x41", "0xd49", "ARM Neoverse-N2"},
        {"0x41", "0xd08", "ARM Cortex-A72"},     // Raspberry Pi 4
        {"0x41", "0xd03", "ARM Cortex-A53"},
        {"0xc0", "0xac3", "Ampere-1"},          // not "Ampere Ampere-1"
        {"0x61", "0x022", "Apple M1"},           // must not stutter "Apple Apple M1"
        {"65",   "3340",  "ARM Neoverse-N1"},    // decimal-formatted kernels
    };
    for (const auto& c : cases) {
        const std::string got = arm::model_name(c.impl, c.part);
        check(got == c.want, std::string(c.impl) + "/" + c.part + " -> \"" + got +
                                 "\"" + (got == c.want ? std::string() : " (wanted \"" + std::string(c.want) + "\")"));
    }

    // A known vendor with an unknown part still beats "CPU" in a bug report.
    {
        const std::string got = arm::model_name("0x41", "0xfff");
        check(got.rfind("ARM", 0) == 0 && got.find("fff") != std::string::npos,
              "unknown ARM part degrades to vendor + raw id (" + got + ")");
    }
    // Total garbage yields "", so the caller falls through to the board name.
    check(arm::model_name("", "").empty(), "empty ids yield no name");
    check(arm::model_name("0x99", "0x1").empty(), "unknown implementer yields no name");
}

// The "work is on the slow cores" advisory (issue #3's second ask). Pinned at
// the boundaries because a threshold that quietly stops firing still compiles
// and still looks reasonable — it just never speaks again.
void test_cluster_skew() {
    std::printf("\nissue #3 — work-on-slow-cores advisory:\n");

    // Build 4 E + 4 P cores at the given loads (percent).
    auto mk = [](double eff_pct, double perf_pct) {
        std::vector<CpuCore> v(8);
        for (int i = 0; i < 8; ++i) {
            const bool e = i < 4;
            v[static_cast<std::size_t>(i)].kind = e ? CoreKind::Eff : CoreKind::Perf;
            v[static_cast<std::size_t>(i)].usage = Ratio{(e ? eff_pct : perf_pct) / 100.0};
        }
        return v;
    };

    {
        const ClusterLoad c = cluster_load(mk(100, 5));
        check(c.eff_n == 4 && c.perf_n == 4, "counts both clusters");
        check(c.eff_avg > 99 && c.perf_avg < 6, "averages per cluster, not overall");
        check(c.misplaced(), "E pegged + P idle -> advise");
    }
    // The whole machine is busy: there is nowhere faster to move the work, so
    // the advice would be noise.
    check(!cluster_load(mk(100, 95)).misplaced(), "both clusters busy -> stay quiet");
    // Light background work on the E cluster is what it is FOR.
    check(!cluster_load(mk(40, 5)).misplaced(), "idle-ish E cluster -> stay quiet");
    // Inverted: heavy on P, quiet on E. Correct scheduling; nothing to say.
    check(!cluster_load(mk(5, 100)).misplaced(), "work already on P -> stay quiet");
    // Boundaries: strictly greater / strictly less.
    check(!cluster_load(mk(70, 10)).misplaced(), "E exactly at the 70% floor -> quiet");
    check(cluster_load(mk(71, 10)).misplaced(), "E just over the floor -> advise");
    check(!cluster_load(mk(90, 30)).misplaced(), "P exactly at the 30% ceiling -> quiet");
    check(cluster_load(mk(90, 29)).misplaced(), "P just under the ceiling -> advise");
    // A homogeneous machine has no clusters to be wrong about.
    {
        std::vector<CpuCore> flat(8);
        for (auto& c : flat) c.usage = Ratio{1.0};
        check(!cluster_load(flat).misplaced(), "homogeneous machine never advises");
    }
}

// The version must come from ONE place (the project() line in CMakeLists.txt,
// via the generated core/version.hpp). A second copy in a string literal is
// how a project ends up announcing the wrong number from a correct binary —
// invisible until it lands in someone's bug report.
void test_version() {
    std::printf("\nversion is centralised:\n");

    const std::string v = kVersion;
    check(!v.empty(), "version is non-empty");

    // Shape: major.minor.patch, digits and dots only.
    int dots = 0;
    bool shape_ok = !v.empty();
    for (char ch : v) {
        if (ch == '.') ++dots;
        else if (!std::isdigit(static_cast<unsigned char>(ch))) shape_ok = false;
    }
    check(shape_ok && dots == 2, "version is major.minor.patch (" + v + ")");

    // The components must agree with the string — they all come from the same
    // configure_file expansion, so a mismatch means the template drifted.
    const std::string from_parts = std::to_string(kVersionMajor) + "." +
                                   std::to_string(kVersionMinor) + "." +
                                   std::to_string(kVersionPatch);
    check(from_parts == v, "numeric components match the string (" + from_parts + ")");

    // And the line `rb --version` prints must be derived from it, not typed.
    const std::string line = kVersionLine;
    check(line == "rockbottom " + v, "--version line derives from it (" + line + ")");

    // The real check: parse_args must emit exactly that line. This is what
    // actually regressed — config.hpp used to hardcode "rockbottom 1.0" while
    // CMake said 1.0.0.
    {
        Config c;
        std::string msg;
        bool ok = false;
        char arg0[] = "rb", arg1[] = "--version";
        char* argv[] = {arg0, arg1};
        const bool cont = Config::parse_args(2, argv, c, msg, ok);
        check(!cont && ok, "--version exits cleanly");
        check(msg == line + "\n", "rb --version prints \"" + line + "\"");
    }
}

// Per-core temperature resolution. The interesting case is the one Apple
// Silicon actually presents: the platform publishes a temperature PER CLUSTER,
// not per core, and before this the whole column rendered as dashes. Driven
// through the public Sampler so the real resolution path runs.
void test_core_temps() {
    std::printf("\nper-core temperature resolution:\n");

    // A cluster-labelled sensor must reach every core of that cluster, and
    // must NOT bleed across into the other one.
    {
        CpuInfo cpu = make_cpu(8, true, 0);   // hybrid, no per-core temps
        std::vector<Sensor> sensors{
            {"CPU performance", "cpu", 74.4f, 0, 0},
            {"CPU efficiency",  "cpu", 64.3f, 0, 0},
        };
        resolve_core_temps(cpu, sensors, {});

        bool perf_ok = true, eff_ok = true;
        for (const CpuCore& c : cpu.cores) {
            if (c.kind == CoreKind::Perf && std::abs(c.temp_c - 74.4f) > 0.01f) perf_ok = false;
            if (c.kind == CoreKind::Eff  && std::abs(c.temp_c - 64.3f) > 0.01f) eff_ok  = false;
        }
        check(perf_ok, "cluster sensor fans out to every P core");
        check(eff_ok,  "cluster sensor fans out to every E core");
        // Package = hottest CPU-zone reading, so "is anything cooking?" is
        // answerable; a mean would hide exactly that.
        check(std::abs(cpu.temp_c - 74.4f) < 0.01f,
              "package temp is the hottest CPU sensor (" + std::to_string(cpu.temp_c) + ")");
    }

    // A real PER-CORE sensor must win over the cluster fallback.
    {
        CpuInfo cpu = make_cpu(4, false, 0);
        for (CpuCore& c : cpu.cores) c.kind = CoreKind::Perf;
        std::vector<Sensor> sensors{
            {"Core 2",          "cpu", 91.0f, 0, 0},
            {"CPU performance", "cpu", 70.0f, 0, 0},
        };
        std::unordered_map<int, std::vector<int>> by_core_id{{2, {2}}};
        resolve_core_temps(cpu, sensors, by_core_id);
        check(std::abs(cpu.cores[2].temp_c - 91.0f) < 0.01f,
              "per-core sensor beats the cluster average");
        check(std::abs(cpu.cores[0].temp_c - 70.0f) < 0.01f,
              "cores without their own sensor still get the cluster figure");
    }

    // Nothing readable: everything stays at the sentinel so the UI omits the
    // column rather than printing a confident zero.
    {
        CpuInfo cpu = make_cpu(4, false, 0);
        resolve_core_temps(cpu, {}, {});
        bool all_zero = cpu.temp_c == 0;
        for (const CpuCore& c : cpu.cores) if (c.temp_c != 0) all_zero = false;
        check(all_zero, "no sensors -> no invented temperatures");
    }
}

